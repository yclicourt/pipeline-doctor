describe("checkDeps with OSV retries", () => {
  function retryOpts(notices: RetryNotice[]): RetryOptions {
    return {
      sleep: instantSleep,
      onRetry: (notice) => notices.push(notice),
    };
  }

  it("recovers when the querybatch call fails once with a network error", async () => {
    const dir = tempDir();
    try {
      writeFileSync(join(dir, "package-lock.json"), PACKAGE_LOCK_V3);
      const stub = flakyStubFetch(
        { "lodash@4.17.20": [LODASH_VULN] },
        { failTimes: 1, throws: new Error("fetch failed") },
      );
      const notices: RetryNotice[] = [];
      const result = await checkDeps(dir, stub.fetch, retryOpts(notices));
      // 1 failed batch + 1 good batch + 1 detail fetch.
      expect(stub.calls()).toBe(3);
      expect(notices).toHaveLength(1);
      expect(notices[0]).toMatchObject({
        attempt: 1,
        attempts: 3,
        reason: "fetch failed",
        delayMs: 1000,
      });
      expect(result.findings).toHaveLength(1);
      expect(result.findings[0]?.detail).toContain("GHSA-35jh-r3h4-6jhm");
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it("recovers when OSV answers 429 once", async () => {
    const dir = tempDir();
    try {
      writeFileSync(join(dir, "package-lock.json"), PACKAGE_LOCK_V3);
      const stub = flakyStubFetch(
        { "lodash@4.17.20": [LODASH_VULN] },
        { failTimes: 1, status: 429 },
      );
      const notices: RetryNotice[] = [];
      const result = await checkDeps(dir, stub.fetch, retryOpts(notices));
      expect(stub.calls()).toBe(3);
      expect(notices).toHaveLength(1);
      expect(notices[0]?.reason).toBe("HTTP 429");
      expect(result.findings).toHaveLength(1);
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it("recovers when a detail fetch fails once", async () => {
    const dir = tempDir();
    try {
      writeFileSync(join(dir, "package-lock.json"), PACKAGE_LOCK_V3);
      const stub = flakyStubFetch(
        { "lodash@4.17.20": [LODASH_VULN] },
        { failTimes: 1, throws: new Error("fetch failed"), onlyDetail: true },
      );
      const notices: RetryNotice[] = [];
      const result = await checkDeps(dir, stub.fetch, retryOpts(notices));
      // 1 good batch + 1 failed detail + 1 good detail.
      expect(stub.calls()).toBe(3);
      expect(notices).toHaveLength(1);
      expect(result.findings).toHaveLength(1);
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it("still throws after the retries are exhausted (network)", async () => {
    const dir = tempDir();
    try {
      writeFileSync(join(dir, "package-lock.json"), PACKAGE_LOCK_V3);
      const stub = flakyStubFetch(
        {},
        { failTimes: 10, throws: new Error("fetch failed") },
      );
      const notices: RetryNotice[] = [];
      await expect(
        checkDeps(dir, stub.fetch, retryOpts(notices)),
      ).rejects.toThrow(/OSV API request failed/);
      // 3 attempts total, then the fail-loudly throw — never a silent pass.
      expect(stub.calls()).toBe(3);
      expect(notices.map((n) => n.delayMs)).toEqual([1000, 2000]);
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it("still throws after the retries are exhausted (HTTP 500)", async () => {
    const dir = tempDir();
    try {
      writeFileSync(join(dir, "package-lock.json"), PACKAGE_LOCK_V3);
      const stub = flakyStubFetch({}, { failTimes: 10, status: 500 });
      const notices: RetryNotice[] = [];
      await expect(
        checkDeps(dir, stub.fetch, retryOpts(notices)),
      ).rejects.toThrow(/OSV API request failed: HTTP 500/);
      expect(stub.calls()).toBe(3);
      expect(notices).toHaveLength(2);
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it("does NOT retry a non-retryable 4xx — it fails at once", async () => {
    const dir = tempDir();
    try {
      writeFileSync(join(dir, "package-lock.json"), PACKAGE_LOCK_V3);
      const stub = flakyStubFetch({}, { failTimes: 10, status: 400 });
      const notices: RetryNotice[] = [];
      await expect(
        checkDeps(dir, stub.fetch, retryOpts(notices)),
      ).rejects.toThrow(/OSV API request failed: HTTP 400/);
      expect(stub.calls()).toBe(1);
      expect(notices).toHaveLength(0);
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });
});

