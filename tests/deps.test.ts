describe("parsePackageLock", () => {
  it("reads a v3 lockfile (packages map, scoped names, root skipped)", () => {
    const deps = parsePackageLock(PACKAGE_LOCK_V3, "package-lock.json");
    expect(deps).toHaveLength(3);
    const lodash = deps.find((d) => d.name === "lodash");
    expect(lodash).toMatchObject({ version: "4.17.20", file: "package-lock.json" });
    // The line of the "node_modules/lodash": { entry.
    expect(lodash?.line).toBe(11);
    expect(deps.find((d) => d.name === "@scope/pkg")?.version).toBe("1.2.3");
    expect(deps.find((d) => d.name === "clean-dep")?.version).toBe("2.0.0");
  });

  it("reads a v1 lockfile (nested dependencies)", () => {
    const deps = parsePackageLock(PACKAGE_LOCK_V1, "package-lock.json");
    expect(deps.map((d) => `${d.name}@${d.version}`).sort()).toEqual([
      "clean-dep@2.0.0",
      "lodash@4.17.20",
      "nested@0.1.0",
    ]);
    expect(deps.find((d) => d.name === "lodash")?.line).toBe(6);
  });

  it("throws on unparseable JSON", () => {
    expect(() => parsePackageLock("{not json", "package-lock.json")).toThrow(
      /failed to parse/,
    );
  });
});

