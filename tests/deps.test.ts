interface StubOptions {
  status?: number;
  throws?: Error;
}

/**
 * A fake fetch that answers like the real OSV API: querybatch returns
 * minimal records (`id` + `modified` only) and the full record comes
 * from GET /v1/vulns/{id}. The stub keeps both shapes honest — a
 * querybatch-only implementation cannot pass these tests.
 */
function stubFetch(
  vulnsByDep: Record<string, { id: string }[]>,
  opts: StubOptions = {},
) {
  let calls = 0;
  const byId = new Map<string, unknown>();
  for (const vulns of Object.values(vulnsByDep)) {
    for (const vuln of vulns) byId.set(vuln.id, vuln);
  }
  const fn = (async (url: string, init?: { body?: unknown }) => {
    calls++;
    if (opts.throws !== undefined) throw opts.throws;
    const status = opts.status ?? 200;
    if (url.includes("/vulns/")) {
      const id = decodeURIComponent(url.split("/vulns/")[1] as string);
      return {
        ok: status >= 200 && status < 300,
        status,
        json: async () => byId.get(id) ?? {},
      };
    }
    const body = JSON.parse(String(init?.body ?? "{}")) as {
      queries: { package: { name: string }; version: string }[];
    };
    const results = body.queries.map((q) => {
      const vulns = vulnsByDep[`${q.package.name}@${q.version}`];
      return vulns !== undefined && vulns.length > 0
        ? {
            vulns: vulns.map((v) => ({
              id: v.id,
              modified: "2026-01-01T00:00:00Z",
            })),
          }
        : {};
    });
    return {
      ok: status >= 200 && status < 300,
      status,
      json: async () => ({ results }),
    };
  }) as unknown as typeof fetch;
  return { fetch: fn, calls: () => calls };
}

function tempDir(): string {
  return mkdtempSync(join(tmpdir(), "pd-deps-"));
}

/** Backoff sleep that returns at once — retry tests must not wait ~3s. */
const instantSleep: RetryOptions["sleep"] = async () => {};

const silentRetry: Pick<RetryOptions, "onRetry"> = { onRetry: () => {} };

/**
 * A stub fetch that fails the first `failTimes` matching calls
 * (network error or HTTP status), then behaves like the normal OSV
 * stub. With `onlyDetail`, only GET /v1/vulns/ calls fail — the
 * querybatch call still succeeds on its first attempt.
 */
function flakyStubFetch(
  vulnsByDep: Record<string, { id: string }[]>,
  opts: { failTimes: number; throws?: Error; status?: number; onlyDetail?: boolean },
) {
  const base = stubFetch(vulnsByDep);
  let failed = 0;
  let calls = 0;
  const fn = (async (url: string, init?: { body?: unknown }) => {
    calls++;
    const isDetail = url.includes("/vulns/");
    const matches = opts.onlyDetail === true ? isDetail : true;
    if (failed < opts.failTimes && matches) {
      failed++;
      if (opts.throws !== undefined) throw opts.throws;
      return {
        ok: false,
        status: opts.status ?? 500,
        json: async () => ({}),
      };
    }
    return base.fetch(url, init);
  }) as unknown as typeof fetch;
  return { fetch: fn, calls: () => calls };
}

